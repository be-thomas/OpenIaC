// Package pulumi emits TypeScript Pulumi programs targeting @pulumi/aws.
package pulumi

import (
	"fmt"
	"sort"
	"strings"

	"github.com/be-thomas/openiac/pkg/emitters"
	"github.com/be-thomas/openiac/pkg/emitutil"
	"github.com/be-thomas/openiac/pkg/ir"
	"github.com/be-thomas/openiac/pkg/mappings"
)

// Emitter renders graphs as a Pulumi TypeScript program.
type Emitter struct{}

func New() *Emitter { return &Emitter{} }

func (e *Emitter) Name() string { return "pulumi" }

type run struct {
	graph        *ir.Graph
	registry     *mappings.Registry
	warnings     *emitters.Warnings
	identByID    map[string]string
	resourceByID map[string]*ir.Resource
	varIdents    map[string]string
	usedAWS      bool
}

func (e *Emitter) Emit(graph *ir.Graph, options emitters.Options) (*emitters.Result, error) {
	registry, err := mappings.Load()
	if err != nil {
		return nil, err
	}
	ordered, err := graph.Order()
	if err != nil {
		return nil, err
	}

	r := &run{
		graph:        graph,
		registry:     registry,
		warnings:     emitters.NewWarnings(),
		identByID:    make(map[string]string, len(graph.Resources)),
		resourceByID: make(map[string]*ir.Resource, len(graph.Resources)),
		varIdents:    make(map[string]string, len(graph.Variables)),
	}
	emitters.WarnUnsupported(graph, r.warnings)

	namer := emitutil.NewNamer()
	for _, reserved := range []string{"pulumi", "aws", "config", "exports"} {
		namer.Reserve(reserved)
	}
	for _, resource := range graph.Resources {
		r.resourceByID[resource.ID] = resource
		r.identByID[resource.ID] = namer.Take(emitutil.ResourceIdent(resource.Provider, resource.Type, resource.Name))
	}
	for _, variable := range graph.Variables {
		r.varIdents["var."+variable.Name] = namer.Take(emitutil.CamelCase(variable.Name))
	}

	rewriter := emitutil.NewRefRewriter(r.addresses(), r.resolve)

	var body strings.Builder
	r.emitVariables(&body, rewriter)
	r.emitResources(&body, ordered, rewriter)
	r.emitOutputs(&body, rewriter)

	var out strings.Builder
	out.WriteString("// Generated by OpenIaC. Review this file before deploying.\n")
	if graph.Source != "" {
		out.WriteString("// Source: " + graph.Source + "\n")
	}
	if len(graph.Variables) > 0 {
		out.WriteString("import * as pulumi from '@pulumi/pulumi';\n")
	}
	if r.usedAWS {
		out.WriteString("import * as aws from '@pulumi/aws';\n")
	}
	out.WriteString("\n")
	if len(graph.Variables) > 0 {
		out.WriteString("const config = new pulumi.Config();\n\n")
	}
	if body.Len() == 0 {
		out.WriteString("// No convertible resources were found.\n")
	} else {
		out.WriteString(body.String())
	}

	return &emitters.Result{
		Files:    []emitters.File{{Path: "index.ts", Content: out.String()}},
		Warnings: r.warnings.List(),
	}, nil
}

func (r *run) addresses() []string {
	addresses := make([]string, 0, len(r.graph.Resources)+len(r.graph.Variables)+len(r.graph.Locals)+len(r.graph.Modules))
	for _, resource := range r.graph.Resources {
		addresses = append(addresses, resource.ID)
	}
	for _, variable := range r.graph.Variables {
		addresses = append(addresses, "var."+variable.Name)
	}
	for _, local := range r.graph.Locals {
		addresses = append(addresses, "local."+local.Name)
	}
	for _, module := range r.graph.Modules {
		addresses = append(addresses, "module."+module.Name)
	}
	return addresses
}

func (r *run) resolve(address, attribute string) (string, bool) {
	if ident, ok := r.identByID[address]; ok {
		resource := r.resourceByID[address]
		if resource.Kind == ir.KindData {
			return "undefined", true
		}
		if attribute == "" {
			return ident, true
		}
		target := emitutil.CamelCase(attribute)
		if mapping, ok := r.registry.Resources[resource.Type]; ok && mapping.Pulumi != nil {
			if override, ok := mapping.Pulumi.Attributes[attribute]; ok {
				target = override
			}
		}
		return ident + "." + target, true
	}
	if ident, ok := r.varIdents[address]; ok {
		return ident, true
	}
	switch {
	case strings.HasPrefix(address, "local."):
		r.warnings.Addf("%s: locals are not converted yet; emitted undefined", address)
		return "undefined", true
	case strings.HasPrefix(address, "module."):
		r.warnings.Addf("%s: modules are not expanded yet; emitted undefined", address)
		return "undefined", true
	}
	return "", false
}

func (r *run) emitVariables(body *strings.Builder, rewriter *emitutil.RefRewriter) {
	for _, variable := range r.graph.Variables {
		ident := r.varIdents["var."+variable.Name]
		getter := "config.get"
		switch {
		case variable.Sensitive:
			getter = "config.getSecret"
		case variable.Default != nil && variable.Default.Kind == ir.KindNumber:
			getter = "config.getNumber"
		case variable.Default != nil && variable.Default.Kind == ir.KindBool:
			getter = "config.getBoolean"
		case variable.Default == nil:
			getter = "config.require"
		}
		body.WriteString(fmt.Sprintf("// var.%s\nconst %s = %s(%s)", variable.Name, ident, getter, emitutil.Quote(variable.Name)))
		if variable.Default != nil {
			body.WriteString(" ?? " + emitutil.RenderValue(*variable.Default, rewriter))
		}
		body.WriteString(";\n\n")
	}
}

func (r *run) emitResources(body *strings.Builder, ordered []*ir.Resource, rewriter *emitutil.RefRewriter) {
	for _, resource := range ordered {
		if resource.Kind == ir.KindData {
			body.WriteString(fmt.Sprintf("// TODO(openiac): data source %s is not converted yet.\n", resource.ID))
			continue
		}
		if resource.Provider != "aws" {
			r.warnings.Addf("%s: provider %q is not supported yet; skipped", resource.ID, resource.Provider)
			body.WriteString(fmt.Sprintf("// TODO(openiac): provider %q is not supported yet (%s).\n", resource.Provider, resource.ID))
			continue
		}
		if resource.ProviderAlias != "" {
			r.warnings.Addf("%s: provider aliases are not supported yet; using the default provider", resource.ID)
		}

		ident := r.identByID[resource.ID]
		pulumiMapping, ok := r.registry.Resources[resource.Type]
		module, class := "", ""
		if ok && pulumiMapping.Pulumi != nil {
			module, class = pulumiMapping.Pulumi.Module, pulumiMapping.Pulumi.Class
		} else if guessedModule, guessedClass, ok := guessMapping(resource.Type); ok {
			module, class = guessedModule, guessedClass
			r.warnings.Addf("%s: no Pulumi mapping; inferred aws.%s.%s", resource.ID, module, class)
		} else {
			r.warnings.Addf("%s: no Pulumi mapping; skipped", resource.ID)
			body.WriteString(fmt.Sprintf("// TODO(openiac): no Pulumi mapping for %s.\n", resource.Type))
			continue
		}

		var mappingPtr *mappings.PulumiMapping
		if ok {
			mappingPtr = pulumiMapping.Pulumi
		}
		r.usedAWS = true
		props := r.renderProperties(resource, mappingPtr, rewriter)
		options := r.renderOptions(resource)

		body.WriteString(fmt.Sprintf("// %s\n", resource.ID))
		if props == "" {
			body.WriteString(fmt.Sprintf("const %s = new aws.%s.%s(%s%s);\n\n",
				ident, module, class, emitutil.Quote(resource.Name), options))
			continue
		}
		body.WriteString(fmt.Sprintf("const %s = new aws.%s.%s(%s, %s%s);\n\n",
			ident, module, class, emitutil.Quote(resource.Name), props, options))
	}
}

func (r *run) renderProperties(resource *ir.Resource, mapping *mappings.PulumiMapping, rewriter *emitutil.RefRewriter) string {
	var lines []string

	// .tf.json leaves nested blocks as flat map/list attributes; recover the
	// shape native HCL would have produced before rendering either one.
	var schema map[string]mappings.BlockMap
	if mapping != nil {
		schema = mapping.Blocks
	}
	flatBlocks, consumed := emitters.UnflattenBlocks(resource.Attributes, schema)
	blocks := resource.Blocks
	if len(flatBlocks) > 0 {
		blocks = append(append([]ir.Block(nil), resource.Blocks...), flatBlocks...)
	}

	for _, name := range sortedKeys(resource.Attributes) {
		if consumed[name] {
			continue
		}
		if name == "count" || name == "for_each" {
			r.warnings.Addf("%s: %s is not supported yet; property skipped", resource.ID, name)
			continue
		}
		property := emitutil.CamelCase(name)
		if mapping != nil {
			if override, ok := mapping.Properties[name]; ok {
				property = override.Name
			}
		}
		value := emitutil.RenderValue(resource.Attributes[name], rewriter)
		lines = append(lines, fmt.Sprintf("  %s: %s,", property, value))
	}

	order, grouped := emitters.GroupBlocks(blocks)
	for _, blockType := range order {
		var blockMap *mappings.BlockMap
		if mapping != nil {
			if mapped, ok := mapping.Blocks[blockType]; ok {
				blockMap = &mapped
			}
		}
		value, ok := r.renderBlockGroup(grouped[blockType], blockMap, rewriter, resource.ID)
		if !ok {
			continue
		}
		property := emitutil.CamelCase(blockType)
		if blockMap != nil && blockMap.Property != "" {
			property = blockMap.Property
		}
		lines = append(lines, fmt.Sprintf("  %s: %s,", property, value))
	}

	if len(lines) == 0 {
		return ""
	}
	return "{\n" + strings.Join(lines, "\n") + "\n}"
}

func (r *run) renderBlockGroup(blocks []ir.Block, blockMap *mappings.BlockMap, rewriter *emitutil.RefRewriter, context string) (string, bool) {
	shape := "array"
	if blockMap != nil && blockMap.Shape != "" {
		shape = blockMap.Shape
	}
	if shape == "presence" {
		if blockMap != nil && blockMap.Value != nil {
			if literal, ok := blockMap.Value.(bool); ok && literal {
				return "true", true
			}
		}
		return "true", true
	}
	if shape == "object" {
		if len(blocks) > 1 {
			r.warnings.Addf("%s: block %q appears %d times; only the first is converted", context, blocks[0].Type, len(blocks))
		}
		return r.renderBlockObject(blocks[0], blockMap, rewriter, context)
	}

	parts := make([]string, 0, len(blocks))
	for _, block := range blocks {
		object, ok := r.renderBlockObject(block, blockMap, rewriter, context)
		if ok {
			parts = append(parts, object)
		}
	}
	if len(parts) == 0 {
		return "", false
	}
	return "[" + strings.Join(parts, ", ") + "]", true
}

func (r *run) renderBlockObject(block ir.Block, blockMap *mappings.BlockMap, rewriter *emitutil.RefRewriter, context string) (string, bool) {
	var parts []string

	var schema map[string]mappings.BlockMap
	if blockMap != nil {
		schema = blockMap.Blocks
	}
	flatBlocks, consumed := emitters.UnflattenBlocks(block.Attributes, schema)
	blocks := block.Blocks
	if len(flatBlocks) > 0 {
		blocks = append(append([]ir.Block(nil), block.Blocks...), flatBlocks...)
	}

	for _, name := range sortedKeys(block.Attributes) {
		if consumed[name] {
			continue
		}
		property := emitutil.CamelCase(name)
		if blockMap != nil {
			if override, ok := blockMap.Properties[name]; ok {
				property = override.Name
			}
		}
		parts = append(parts, fmt.Sprintf("%s: %s", property, emitutil.RenderValue(block.Attributes[name], rewriter)))
	}

	order, grouped := emitters.GroupBlocks(blocks)
	for _, nestedType := range order {
		var nestedMap *mappings.BlockMap
		if blockMap != nil {
			if mapped, ok := blockMap.Blocks[nestedType]; ok {
				nestedMap = &mapped
			}
		}
		value, ok := r.renderBlockGroup(grouped[nestedType], nestedMap, rewriter, context)
		if !ok {
			continue
		}
		property := emitutil.CamelCase(nestedType)
		if nestedMap != nil && nestedMap.Property != "" {
			property = nestedMap.Property
		}
		parts = append(parts, fmt.Sprintf("%s: %s", property, value))
	}

	if len(parts) == 0 {
		r.warnings.Addf("%s: block %q produced no properties; skipped", context, block.Type)
		return "", false
	}
	return "{ " + strings.Join(parts, ", ") + " }", true
}

func (r *run) renderOptions(resource *ir.Resource) string {
	var dependencies []string
	for _, dependency := range resource.DependsOn {
		if ident, ok := r.identByID[dependency]; ok {
			dependencies = append(dependencies, ident)
		}
	}
	if len(dependencies) == 0 {
		return ""
	}
	sort.Strings(dependencies)
	return ", { dependsOn: [" + strings.Join(dependencies, ", ") + "] }"
}

func (r *run) emitOutputs(body *strings.Builder, rewriter *emitutil.RefRewriter) {
	for _, output := range r.graph.Outputs {
		body.WriteString(fmt.Sprintf("// output.%s\nexport const %s = %s;\n\n",
			output.Name, emitutil.CamelCase(output.Name), emitutil.RenderValue(output.Value, rewriter)))
	}
}

// guessMapping derives a Pulumi module and class for AWS resources missing
// from the registry.
func guessMapping(resourceType string) (module, class string, ok bool) {
	parts := strings.Split(resourceType, "_")
	if len(parts) < 2 || parts[0] != "aws" {
		return "", "", false
	}
	token := parts[1]
	if alias, exists := moduleAliases[token]; exists {
		token = alias
	}
	if len(parts) == 2 {
		return token, emitutil.PascalCase(parts[1]), true
	}
	return token, emitutil.PascalCase(strings.Join(parts[2:], "_")), true
}

var moduleAliases = map[string]string{
	"eip":              "ec2",
	"instance":         "ec2",
	"vpc":              "ec2",
	"subnet":           "ec2",
	"security_group":   "ec2",
	"internet_gateway": "ec2",
	"route_table":      "ec2",
	"nat_gateway":      "ec2",
	"network_acl":      "ec2",
	"key_pair":         "ec2",
	"lb":               "lb",
	"rds_instance":     "rds",
}

func sortedKeys(values map[string]ir.Value) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
