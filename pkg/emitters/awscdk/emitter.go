// Package awscdk emits TypeScript AWS CDK (aws-cdk-lib) constructs.
package awscdk

import (
	"fmt"
	"sort"
	"strings"

	"github.com/be-thomas/openiac/pkg/emitters"
	"github.com/be-thomas/openiac/pkg/emitutil"
	"github.com/be-thomas/openiac/pkg/ir"
	"github.com/be-thomas/openiac/pkg/mappings"
)

// Emitter renders graphs as an AWS CDK stack.
type Emitter struct{}

func New() *Emitter { return &Emitter{} }

func (e *Emitter) Name() string { return "cdk" }

type run struct {
	graph        *ir.Graph
	registry     *mappings.Registry
	warnings     *emitters.Warnings
	identByID    map[string]string
	resourceByID map[string]*ir.Resource
	varIdents    map[string]string
	usedModules  map[string]bool
}

func (e *Emitter) Emit(graph *ir.Graph, options emitters.Options) (*emitters.Result, error) {
	registry, err := mappings.Load()
	if err != nil {
		return nil, err
	}
	ordered, err := graph.Order()
	if err != nil {
		return nil, err
	}

	r := &run{
		graph:        graph,
		registry:     registry,
		warnings:     emitters.NewWarnings(),
		identByID:    make(map[string]string, len(graph.Resources)),
		resourceByID: make(map[string]*ir.Resource, len(graph.Resources)),
		varIdents:    make(map[string]string, len(graph.Variables)),
		usedModules:  make(map[string]bool),
	}
	emitters.WarnUnsupported(graph, r.warnings)

	namer := emitutil.NewNamer()
	for _, reserved := range []string{"cdk", "Construct", "Stack"} {
		namer.Reserve(reserved)
	}
	for _, resource := range graph.Resources {
		r.resourceByID[resource.ID] = resource
		r.identByID[resource.ID] = namer.Take(emitutil.ResourceIdent(resource.Provider, resource.Type, resource.Name))
	}
	for _, variable := range graph.Variables {
		r.varIdents["var."+variable.Name] = namer.Take(emitutil.CamelCase(variable.Name))
	}

	rewriter := emitutil.NewRefRewriter(r.addresses(), r.resolve)

	var body strings.Builder
	r.emitVariables(&body, rewriter)
	r.emitResources(&body, ordered, rewriter)
	r.emitOutputs(&body, rewriter)
	r.emitDependencies(&body, ordered)

	stackName := options.StackName
	if stackName == "" {
		stackName = "OpenIacStack"
	}
	stackName = emitutil.PascalCase(stackName)

	var out strings.Builder
	out.WriteString("// Generated by OpenIaC. Review this file before deploying.\n")
	if graph.Source != "" {
		out.WriteString("// Source: " + graph.Source + "\n")
	}
	out.WriteString("import * as cdk from 'aws-cdk-lib';\n")
	for _, module := range sortedModules(r.usedModules) {
		out.WriteString(fmt.Sprintf("import * as %s from 'aws-cdk-lib/%s';\n", moduleAlias(module), module))
	}
	out.WriteString("import { Construct } from 'constructs';\n\n")
	out.WriteString(fmt.Sprintf("export interface %sProps extends cdk.StackProps {}\n\n", stackName))
	out.WriteString(fmt.Sprintf("export class %s extends cdk.Stack {\n", stackName))
	out.WriteString(fmt.Sprintf("  constructor(scope: Construct, id: string, props: %sProps = {}) {\n", stackName))
	out.WriteString("    super(scope, id, props);\n\n")
	if body.Len() == 0 {
		out.WriteString("    // No convertible resources were found.\n")
	} else {
		out.WriteString(body.String())
	}
	out.WriteString("  }\n}\n")

	return &emitters.Result{
		Files:    []emitters.File{{Path: "index.ts", Content: out.String()}},
		Warnings: r.warnings.List(),
	}, nil
}

func (r *run) addresses() []string {
	addresses := make([]string, 0, len(r.graph.Resources)+len(r.graph.Variables)+len(r.graph.Locals)+len(r.graph.Modules))
	for _, resource := range r.graph.Resources {
		addresses = append(addresses, resource.ID)
	}
	for _, variable := range r.graph.Variables {
		addresses = append(addresses, "var."+variable.Name)
	}
	for _, local := range r.graph.Locals {
		addresses = append(addresses, "local."+local.Name)
	}
	for _, module := range r.graph.Modules {
		addresses = append(addresses, "module."+module.Name)
	}
	return addresses
}

func (r *run) resolve(address, attribute string) (string, bool) {
	if ident, ok := r.identByID[address]; ok {
		resource := r.resourceByID[address]
		if resource.Kind == ir.KindData {
			return "undefined", true
		}
		if attribute == "" {
			return ident, true
		}
		target := ""
		if mapping, ok := r.registry.Resources[resource.Type]; ok && mapping.CDK != nil {
			target = mapping.CDK.Attributes[attribute]
		}
		if target == "" {
			r.warnings.Addf("%s: attribute %q has no CDK mapping; output uses .%s", resource.ID, attribute, attribute)
			target = attribute
		}
		return ident + "." + target, true
	}
	if ident, ok := r.varIdents[address]; ok {
		return ident, true
	}
	switch {
	case strings.HasPrefix(address, "local."):
		r.warnings.Addf("%s: locals are not converted yet; emitted undefined", address)
		return "undefined", true
	case strings.HasPrefix(address, "module."):
		r.warnings.Addf("%s: modules are not expanded yet; emitted undefined", address)
		return "undefined", true
	}
	return "", false
}

func (r *run) emitVariables(body *strings.Builder, rewriter *emitutil.RefRewriter) {
	for _, variable := range r.graph.Variables {
		ident := r.varIdents["var."+variable.Name]
		if variable.Default != nil {
			body.WriteString(fmt.Sprintf("    // var.%s\n    const %s = this.node.tryGetContext(%s) ?? %s;\n",
				variable.Name, ident, emitutil.Quote(variable.Name), emitutil.RenderValue(*variable.Default, rewriter)))
			continue
		}
		body.WriteString(fmt.Sprintf("    // var.%s\n    const %s = this.node.tryGetContext(%s);\n",
			variable.Name, ident, emitutil.Quote(variable.Name)))
	}
	if len(r.graph.Variables) > 0 {
		body.WriteString("\n")
	}
}

func (r *run) emitResources(body *strings.Builder, ordered []*ir.Resource, rewriter *emitutil.RefRewriter) {
	for _, resource := range ordered {
		if resource.Kind == ir.KindData {
			body.WriteString(fmt.Sprintf("    // TODO(openiac): data source %s is not converted yet.\n", resource.ID))
			continue
		}
		ident := r.identByID[resource.ID]
		mapping, ok := r.registry.Resources[resource.Type]
		if !ok || mapping.CDK == nil {
			r.warnings.Addf("%s: no CDK mapping; emitted a CfnResource placeholder", resource.ID)
			body.WriteString(fmt.Sprintf("    // TODO(openiac): add a CDK mapping for %s in pkg/mappings/aws.json.\n", resource.Type))
			body.WriteString(fmt.Sprintf("    const %s = new cdk.CfnResource(this, %s, { type: 'AWS::TODO::%s' });\n",
				ident, emitutil.Quote(resource.ID), resource.Type))
			continue
		}

		r.usedModules[mapping.CDK.Module] = true
		props := r.renderProperties(resource, mapping.CDK, rewriter)
		body.WriteString(fmt.Sprintf("    // %s\n", resource.ID))
		if props == "" {
			body.WriteString(fmt.Sprintf("    const %s = new %s(this, %s);\n",
				ident, classRef(mapping.CDK), emitutil.Quote(resource.ID)))
			continue
		}
		body.WriteString(fmt.Sprintf("    const %s = new %s(this, %s, %s);\n",
			ident, classRef(mapping.CDK), emitutil.Quote(resource.ID), props))
	}
	if len(ordered) > 0 {
		body.WriteString("\n")
	}
}

func (r *run) renderProperties(resource *ir.Resource, mapping *mappings.CDKMapping, rewriter *emitutil.RefRewriter) string {
	var lines []string

	// .tf.json leaves nested blocks as flat map/list attributes; recover the
	// shape native HCL would have produced before rendering either one.
	var schema map[string]mappings.BlockMap
	if mapping != nil {
		schema = mapping.Blocks
	}
	flatBlocks, consumed := emitters.UnflattenBlocks(resource.Attributes, schema, resource.Blocks)
	blocks := resource.Blocks
	if len(flatBlocks) > 0 {
		blocks = append(append([]ir.Block(nil), resource.Blocks...), flatBlocks...)
	}

	names := sortedKeys(resource.Attributes)
	for _, name := range names {
		if consumed[name] {
			continue
		}
		if name == "count" || name == "for_each" {
			r.warnings.Addf("%s: %s is not supported yet; property skipped", resource.ID, name)
			continue
		}
		prop, ok := mapping.Properties[name]
		if !ok {
			r.warnings.Addf("%s: property %q has no CDK mapping; skipped", resource.ID, name)
			continue
		}
		value, ok := r.transform(prop.Transform, resource.Attributes[name], rewriter, resource.ID+"."+name)
		if !ok {
			continue
		}
		lines = append(lines, fmt.Sprintf("      %s: %s,", prop.Name, value))
	}

	order, grouped := emitters.GroupBlocks(blocks)
	for _, blockType := range order {
		blockMap, ok := mapping.Blocks[blockType]
		if !ok {
			r.warnings.Addf("%s: block %q has no CDK mapping; skipped", resource.ID, blockType)
			continue
		}
		value, ok := r.renderBlockGroup(grouped[blockType], blockMap, rewriter, resource.ID)
		if !ok {
			continue
		}
		lines = append(lines, fmt.Sprintf("      %s: %s,", blockMap.Property, value))
	}

	if len(lines) == 0 {
		return ""
	}
	return "{\n" + strings.Join(lines, "\n") + "\n    }"
}

func (r *run) renderBlockGroup(blocks []ir.Block, blockMap mappings.BlockMap, rewriter *emitutil.RefRewriter, context string) (string, bool) {
	switch blockMap.Shape {
	case "presence":
		if blockMap.Value != nil {
			literal, ok := blockMap.Value.(bool)
			if ok && literal {
				return "true", true
			}
		}
		return "true", true
	case "object":
		if len(blocks) > 1 {
			r.warnings.Addf("%s: block %q appears %d times; only the first is converted", context, blockMap.Property, len(blocks))
		}
		return r.renderBlockObject(blocks[0], blockMap, rewriter, context)
	default:
		parts := make([]string, 0, len(blocks))
		for _, block := range blocks {
			object, ok := r.renderBlockObject(block, blockMap, rewriter, context)
			if ok {
				parts = append(parts, object)
			}
		}
		if len(parts) == 0 {
			return "", false
		}
		return "[" + strings.Join(parts, ", ") + "]", true
	}
}

func (r *run) renderBlockObject(block ir.Block, blockMap mappings.BlockMap, rewriter *emitutil.RefRewriter, context string) (string, bool) {
	var parts []string

	flatBlocks, consumed := emitters.UnflattenBlocks(block.Attributes, blockMap.Blocks, block.Blocks)
	blocks := block.Blocks
	if len(flatBlocks) > 0 {
		blocks = append(append([]ir.Block(nil), block.Blocks...), flatBlocks...)
	}

	for _, name := range sortedKeys(block.Attributes) {
		if consumed[name] {
			continue
		}
		prop, ok := blockMap.Properties[name]
		if !ok {
			r.warnings.Addf("%s: block %q property %q has no CDK mapping; skipped", context, block.Type, name)
			continue
		}
		value, ok := r.transform(prop.Transform, block.Attributes[name], rewriter, context+"."+block.Type+"."+name)
		if !ok {
			continue
		}
		parts = append(parts, fmt.Sprintf("%s: %s", prop.Name, value))
	}

	order, grouped := emitters.GroupBlocks(blocks)
	for _, nestedType := range order {
		nestedMap, ok := blockMap.Blocks[nestedType]
		if !ok {
			r.warnings.Addf("%s: nested block %q has no CDK mapping; skipped", context, nestedType)
			continue
		}
		value, ok := r.renderBlockGroup(grouped[nestedType], nestedMap, rewriter, context)
		if !ok {
			continue
		}
		parts = append(parts, fmt.Sprintf("%s: %s", nestedMap.Property, value))
	}

	if len(parts) == 0 {
		r.warnings.Addf("%s: block %q produced no properties; skipped", context, block.Type)
		return "", false
	}
	return "{ " + strings.Join(parts, ", ") + " }", true
}

func (r *run) transform(transform string, value ir.Value, rewriter *emitutil.RefRewriter, context string) (string, bool) {
	switch transform {
	case "":
		return emitutil.RenderValue(value, rewriter), true
	case "cfnTags":
		tags, ok := emitutil.TagsToCfn(value, rewriter)
		if !ok {
			r.warnings.Addf("%s: tags must be a literal map for CloudFormation; skipped", context)
			return "", false
		}
		return tags, true
	case "json":
		if value.Kind == ir.KindMap {
			return emitutil.RenderValue(value, rewriter), true
		}
		return "JSON.parse(" + emitutil.RenderValue(value, rewriter) + ")", true
	case "first":
		if value.Kind == ir.KindList {
			if len(value.Items) == 0 {
				r.warnings.Addf("%s: empty list; property skipped", context)
				return "", false
			}
			if len(value.Items) > 1 {
				r.warnings.Addf("%s: list has %d items; only the first is used", context, len(value.Items))
			}
			return emitutil.RenderValue(value.Items[0], rewriter), true
		}
		r.warnings.Addf("%s: expected a literal list; review the generated value", context)
		return emitutil.RenderValue(value, rewriter), true
	default:
		r.warnings.Addf("%s: unknown transform %q; value rendered unchanged", context, transform)
		return emitutil.RenderValue(value, rewriter), true
	}
}

func (r *run) emitOutputs(body *strings.Builder, rewriter *emitutil.RefRewriter) {
	for _, output := range r.graph.Outputs {
		value := emitutil.RenderValue(output.Value, rewriter)
		body.WriteString(fmt.Sprintf("    // output.%s\n    new cdk.CfnOutput(this, %s, { value: %s });\n",
			output.Name, emitutil.Quote(output.Name), value))
	}
	if len(r.graph.Outputs) > 0 {
		body.WriteString("\n")
	}
}

func (r *run) emitDependencies(body *strings.Builder, ordered []*ir.Resource) {
	for _, resource := range ordered {
		if resource.Kind == ir.KindData {
			continue
		}
		from := r.identByID[resource.ID]
		for _, dependency := range resource.DependsOn {
			to, ok := r.identByID[dependency]
			if !ok {
				continue
			}
			body.WriteString(fmt.Sprintf("    %s.node.addDependency(%s);\n", from, to))
		}
	}
}

func classRef(mapping *mappings.CDKMapping) string {
	return moduleAlias(mapping.Module) + "." + mapping.Class
}

func moduleAlias(module string) string {
	alias := strings.TrimPrefix(module, "aws-")
	alias = strings.ReplaceAll(alias, "-", "")
	return emitutil.Sanitize(alias)
}

func sortedModules(used map[string]bool) []string {
	modules := make([]string, 0, len(used))
	for module := range used {
		modules = append(modules, module)
	}
	sort.Strings(modules)
	return modules
}

func sortedKeys(values map[string]ir.Value) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
